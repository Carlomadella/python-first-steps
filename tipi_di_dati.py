# TIPI DI DATI

# Dati singoli
# str: x = "ciao"  # stringhe
# int: x = 5  # numeri interi senza virgola
# float: x = 2.5  # numeri con la virgola
# bool: x = True  # può avere come opzioni True o False, sempre con la prima lettera maiuscola

# Collezioni di dati
# list: x = ["Milano", "Genova", "Palermo"] # una lista di dati, diverso dall'array di JS
# tuple: x = ("Milano", "Genova", "Palermo")
# range: x = range(6) # crea una list con i numeri da 1 a 5, equivale a scrivere: x = [0,1,2,3,4,5]
# dict: x = {"nome": "Milano", "abitanti": 1500000} # dictionary
# set: x = {"Milano", "Genova", "Palermo"}

# per sapere il tipo di dato:
x = 14

print(type(x))
# in console uscirà <class 'int'>, indicà che il dato è di tipo int cioè un numero intero
